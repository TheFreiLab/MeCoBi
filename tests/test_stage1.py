def test_single_atom_ligand_is_monodentate():
    lig = perception.perceive(Ligand("[Cl-]"))
    assert lig.denticity == 1
    assert lig.coord_atoms == [0]
    assert lig.formal_charge == -1
    assert lig.is_arene is False


def test_pure_hydrocarbon_arene_is_one_centroid_site():
    # p-cymene: only C/H, aromatic ring -> eta6-arene = ONE centroid coordination site
    # (denticity 1), the unified hapticity model (same as an explicit override).
    lig = perception.perceive(Ligand("CC1=CC=C(C(C)C)C=C1"))
    assert lig.is_arene is False
    assert lig.denticity == 1
    assert len(lig.pi_sites) == 1               # the whole ring is one pi-site


def test_declared_arene_override():
    lig = perception.perceive(Ligand("CC1=C(C)C(C)C(C)=C1C", is_arene=True))  # Cp*
    assert lig.denticity == 1


def test_neutral_cp_star_diene_auto_detected():
    # Cp* drawn as a neutral diene (sp3 vertex, two ring C=C): RDKit does not
    # flag it aromatic, but the diene SMARTS catches the eta5 cap automatically
    # and collapses it to one centroid site.
    lig = perception.perceive(Ligand("CC1=C(C)C(C)C(C)=C1C"))  # no is_arene flag
    assert lig.denticity == 1
    assert len(lig.coord_atoms) == 5            # all five ring carbons, one centroid site


def test_anionic_cyclopentadienyl_auto_detected():
    # Aromatic [c-] cyclopentadienyl (Cp-) is an all-carbon eta5 cap = one centroid site.
    lig = perception.perceive(Ligand("[cH-]1cccc1"))
    assert lig.denticity == 1
    assert len(lig.coord_atoms) == 5
    assert lig.pi_sites == [[0, 1, 2, 3, 4]]


def test_functionalised_aromatic_is_not_an_arene_cap():
    # A heteroatom-bearing aromatic (pyridine) must NOT be mistaken for an
    # eta-arene cap — it has a real sigma donor and defers to pydentate.
    ring = perception._carbocyclic_arene_atoms(Chem.MolFromSmiles("c1ccncc1"))
    assert ring is None


def test_trim_to_top_n_helper():
    # 3 candidate donors, keep the 2 most probable (over-prediction).
    kept = perception._trim_to_top_n([1, 4, 7], {1: 0.9, 4: 0.2, 7: 0.8}, 2)
    assert kept == [1, 7]


