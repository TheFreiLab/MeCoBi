def test_names_autogenerated_and_unique():
    import pandas as pd

    # provided name kept; missing one generated; duplicate provided disambiguated.
    df = pd.DataFrame({
        "Name": ["MyPt", None, "MyPt"],
        "Metal": ["Pt", "Zn", "Pd"], "Charge": [2, 2, 2],
        "L1": ["[Cl-]"] * 3, "L2": ["[Cl-]"] * 3,
    })
    names = [c.name for c in inputs.parse_dataframe(df)]
    assert names[0] == "MyPt"
    assert names[1] and names[1] != "MyPt"      # generated, non-empty
    assert names[2] != names[0]                 # duplicate disambiguated
    assert len(set(names)) == 3                  # all unique -> no file overwrite


