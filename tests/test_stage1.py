def test_parse_prototype_csv_named_slots():
    complexes = inputs.parse_csv(PROTOTYPE_CSV)
    assert len(complexes) == 24  # 24 data rows in the prototype CSV

    first = complexes[0]  # Cp_Ir_1: Ir, charge 3, L1 Cp + L2 schiff + L3 [Cl]
    assert first.metal.symbol == "Ir"
    assert first.metal.oxidation_state == 3
    assert len(first.ligands) == 3
    assert first.name == "Cp_Ir_1"


def test_atomic_number_metal_resolves_to_symbol():
    # Row 19 Sq1t_Pt_1 uses atomic number 78 for platinum.
    complexes = inputs.parse_csv(PROTOTYPE_CSV)
    pt_row = next(c for c in complexes if c.name == "Sq1t_Pt_1")
    assert pt_row.metal.symbol == "Pt"
    assert len(pt_row.ligands) == 1


def test_anionic_ligand_charges_and_total_charge():
    # Sq1b_Pt_1: Pt(II) + bipyridine(0) + 2x [Cl-] -> total charge 0.
    complexes = inputs.parse_csv(PROTOTYPE_CSV)
    row = next(c for c in complexes if c.name == "Sq1b_Pt_1")
    charges = sorted(l.formal_charge for l in row.ligands)
    assert charges == [-1, -1, 0]
    assert row.total_charge == 0


def test_carbon_monoxide_normalized_to_neutral():
    # Users write CO as [C]#[O+] (RDKit reads +1 radical cation); it must be
    # normalised to neutral closed-shell [C-]#[O+].
    assert inputs.normalize_smiles("[C]#[O+]") == "[C-]#[O+]"
    cx = inputs.parse_row(["Mn", "1", "[C]#[O+]"])
    co = cx.ligands[0]
    assert co.smiles == "[C-]#[O+]"
    assert co.formal_charge == 0


def test_radical_detection_and_warning():
    # Genuine radical (chlorine atom) is flagged; the anion is clean.
    assert inputs.radical_electrons("[Cl]") == 1
    assert inputs.radical_electrons("[Cl-]") == 0
    assert inputs.radical_warning("[Cl]") is not None
    assert inputs.radical_warning("[Cl-]") is None
    # Auto-normalised inorganic ligands are NOT flagged (already closed-shell).
    assert inputs.radical_electrons("[C]#[O+]") == 0   # -> CO
    assert inputs.radical_electrons("O=[N+][O-]") == 0  # -> nitrite anion


def test_nitrite_radical_normalized_to_anion():
    # O=[N+][O-] is a neutral NO2 radical; normalise to closed-shell nitrite anion.
    assert inputs.normalize_smiles("O=[N+][O-]") == "O=N[O-]"
    cx = inputs.parse_row(["Pt", "2", "O=[N+][O-]", "O=[N+][O-]", "O=[N+][O-]", "O=[N+][O-]"])
    assert all(l.smiles == "O=N[O-]" and l.formal_charge == -1 for l in cx.ligands)
    assert cx.total_charge == -2  # [Pt(NO2)4]2-


def test_co_neutral_makes_octa_row_charge_correct():
    # Oct6_Fe_1: Fe(III) + 3 halide anions + CO(0) + 2 aqua(0) -> neutral.
    complexes = inputs.parse_csv(PROTOTYPE_CSV)
    fe = next(c for c in complexes if c.name == "Oct6_Fe_1")
    assert all(l.formal_charge in (-1, 0) for l in fe.ligands)  # no spurious +1 CO
    assert fe.total_charge == 0


def test_counterions_stripped_and_charge_recomputed():
    # [Ru(bpy)3](PF6)2 written with a spectator Na+ and two PF6-: the counterions
    # must drop out of the ligand list, leaving only the three bipyridines, and
    # the total charge must reflect only the coordination sphere (Ru(II) + 3x
    # neutral bpy = +2), not the padded-out written formula.
    cx = inputs.parse_row(
        ["Ru", "2", "c1ccc(-c2ccccn2)nc1", "c1ccc(-c2ccccn2)nc1",
         "c1ccc(-c2ccccn2)nc1", "[Na+]", "F[P-](F)(F)(F)(F)F", "F[P-](F)(F)(F)(F)F"]
    )
    assert len(cx.ligands) == 3
    assert all(l.formal_charge == 0 for l in cx.ligands)
    assert cx.total_charge == 2
    # Individual classifier: named counterions yes, bare halide NO (it coordinates).
    assert inputs.is_counterion("[Na+]") and inputs.is_counterion("[B-](F)(F)(F)F")
    assert inputs.is_counterion("[O-]S(=O)(=O)C(F)(F)F")  # triflate
    assert not inputs.is_counterion("[Cl-]")
    assert not inputs.is_counterion("c1ccncc1")


